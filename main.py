import streamlit as st
import pandas as pd

# ─────────────────────────────────────────────
# 페이지 기본 설정
# ─────────────────────────────────────────────
st.set_page_config(page_title="청소년 SNS와 정신건강", layout="wide")
st.title("📱 하루 SNS 사용량과 학생 생활 지표 비교")
st.write("당곡고등학교 데이터 탐구 - SNS 사용 시간을 30분 단위로 비교합니다.")

# ─────────────────────────────────────────────
# 데이터 불러오기 (영어 → 한글 번역)
# ─────────────────────────────────────────────
@st.cache_data
def load_data():
    df = pd.read_csv("Teen_Mental_Health_Dataset.csv")

    df["gender"] = df["gender"].map({"male": "남성", "female": "여성"})
    df["platform_usage"] = df["platform_usage"].map({
        "Instagram": "인스타그램", "TikTok": "틱톡", "Both": "둘 다"
    })
    df["social_interaction_level"] = df["social_interaction_level"].map({
        "low": "낮음", "medium": "보통", "high": "높음"
    })

    df = df.rename(columns={
        "age": "나이", "gender": "성별",
        "daily_social_media_hours": "하루SNS사용시간",
        "platform_usage": "사용플랫폼", "sleep_hours": "수면시간",
        "screen_time_before_sleep": "취침전스크린시간",
        "academic_performance": "학업성취도", "physical_activity": "신체활동량",
        "social_interaction_level": "사회적상호작용",
        "stress_level": "스트레스수준", "anxiety_level": "불안수준",
        "addiction_level": "중독수준", "depression_label": "우울증여부"
    })
    return df

df = load_data()

# ─────────────────────────────────────────────
# 숫자를 '○시간 ○분' 형태로 바꿔주는 함수
# ─────────────────────────────────────────────
def 시간표시(숫자):
    시 = int(숫자)
    분 = int(round((숫자 - 시) * 60))
    if 분 == 0:
        return f"{시}시간"
    else:
        return f"{시}시간 {분}분"

# ─────────────────────────────────────────────
# 데이터 미리보기
# ─────────────────────────────────────────────
with st.expander("📋 데이터 미리보기 (클릭하여 펼치기)"):
    st.dataframe(df.head(20))
    st.write(f"전체 학생 수: {len(df)} 명")

# ─────────────────────────────────────────────
# 하루 SNS 사용시간을 0.5시간 단위 구간으로 나누기
# ─────────────────────────────────────────────
최소값 = df["하루SNS사용시간"].min()
최대값 = df["하루SNS사용시간"].max()

시작 = (int(최소값 * 2)) / 2
끝 = (int(최대값 * 2) + 1) / 2

구간경계 = []
값 = 시작
while 값 <= 끝:
    구간경계.append(round(값, 1))
    값 += 0.5

구간이름 = []
for i in range(len(구간경계) - 1):
    구간이름.append(f"{시간표시(구간경계[i])} ~ {시간표시(구간경계[i+1])}")

df["SNS사용구간"] = pd.cut(df["하루SNS사용시간"], bins=구간경계,
                          labels=구간이름, right=False)

# 구간별 평균 계산
평균표 = df.groupby("SNS사용구간")[
    ["수면시간", "학업성취도", "신체활동량", "스트레스수준"]
].mean().round(2)

# 그래프 종류 선택
st.write("---")
그래프종류 = st.radio(
    "보고 싶은 그래프 종류를 선택하세요",
    ["막대그래프", "꺾은선 그래프"],
    horizontal=True
)
st.write("---")

# ─────────────────────────────────────────────
# 평균값을 30분 단위로 반올림하는 함수
# (수면시간, 신체활동량처럼 '시간' 단위 지표에 사용)
# ─────────────────────────────────────────────
def 반올림30분(값):
    return round(값 * 2) / 2   # 0.5 단위로 반올림

# ─────────────────────────────────────────────
# 그래프 그리는 함수
# ─────────────────────────────────────────────
def 그래프그리기(지표이름, 시간단위=False):
    if 그래프종류 == "막대그래프":
        st.bar_chart(평균표[지표이름])
    else:
        st.line_chart(평균표[지표이름])

    # 시간 단위 지표는 30분 단위로 표시한 표를 추가로 보여줌
    if 시간단위:
        표 = 평균표[지표이름].apply(반올림30분).apply(시간표시)
        st.caption("⏰ 30분 단위로 반올림한 값")
        st.dataframe(표.rename("30분 단위 표시"), use_container_width=True)

# ─────────────────────────────────────────────
# 4가지 지표를 각각 따로 그리기
# ─────────────────────────────────────────────
st.header("📊 SNS 사용 구간별 지표 비교 (30분 단위)")

st.subheader("😴 수면시간")
그래프그리기("수면시간", 시간단위=True)   # 시간 단위 → 30분 표시

st.subheader("📚 학업성취도")
그래프그리기("학업성취도")               # 점수 단위 → 그대로

st.subheader("🏃 신체활동량")
그래프그리기("신체활동량", 시간단위=True)  # 시간 단위 → 30분 표시

st.subheader("😣 스트레스수준")
그래프그리기("스트레스수준")             # 점수 단위 → 그대로

# ─────────────────────────────────────────────
# 평균값 표로 정리
# ─────────────────────────────────────────────
st.header("📑 구간별 평균값 표")
st.dataframe(평균표, use_container_width=True)

st.info(
    "💡 참고\n\n"
    "- '수면시간', '신체활동량'은 시간 단위라 30분 단위로 표시했어요.\n"
    "- '학업성취도'(평점), '스트레스수준'(1~10점)은 시간이 아니라서 점수 그대로 표시합니다.\n"
    "- 스트림릿 기본 그래프는 y축 눈금 간격을 직접 바꿀 수 없어, 표로 30분 단위를 보여줍니다."
)
