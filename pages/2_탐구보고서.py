# ─────────────────────────────────────────────
st.set_page_config(page_title="SNS 사용량과 부정적 영향 탐구", layout="wide")
st.title("🔬 SNS를 얼마나 사용하면 부정적 영향이 생길까?")
st.write("당곡고등학교 통계 탐구보고서 - 막대그래프로 경향을 살펴봅니다.")

st.warning(
    "⚠️ 통계 해석 주의: 데이터는 '경향(상관관계)'을 보여줄 뿐, "
    "'SNS 때문이다'라는 인과관계를 완벽히 증명하지는 못합니다. "
    "이 점을 보고서에 꼭 함께 적으면 더 훌륭한 탐구가 됩니다!"
)

# ─────────────────────────────────────────────
# 데이터 불러오기 (영어 → 한글 번역)
# ─────────────────────────────────────────────
@st.cache_data
def load_data():
    df = pd.read_csv("Teen_Mental_Health_Dataset.csv")

    df["gender"] = df["gender"].map({"male": "남성", "female": "여성"})
    df["platform_usage"] = df["platform_usage"].map({
        "Instagram": "인스타그램", "TikTok": "틱톡", "Both": "둘 다"
    })
    df["social_interaction_level"] = df["social_interaction_level"].map({
        "low": "낮음", "medium": "보통", "high": "높음"
    })

    df = df.rename(columns={
        "age": "나이", "gender": "성별",
        "daily_social_media_hours": "하루SNS사용시간",
        "platform_usage": "사용플랫폼", "sleep_hours": "수면시간",
        "screen_time_before_sleep": "취침전스크린시간",
        "academic_performance": "학업성취도", "physical_activity": "신체활동량",
        "social_interaction_level": "사회적상호작용",
        "stress_level": "스트레스수준", "anxiety_level": "불안수준",
        "addiction_level": "중독수준", "depression_label": "우울증여부"
    })
    return df

df = load_data()

# ─────────────────────────────────────────────
# 상관계수를 직접 계산하는 함수 (라이브러리 없이)
# ─────────────────────────────────────────────
def 상관계수(x, y):
    n = len(x)
    if n == 0:
        return 0
    x평균 = sum(x) / n
    y평균 = sum(y) / n
    분자 = sum((x[i] - x평균) * (y[i] - y평균) for i in range(n))
    x분모 = sum((x[i] - x평균) ** 2 for i in range(n)) ** 0.5
    y분모 = sum((y[i] - y평균) ** 2 for i in range(n)) ** 0.5
    if x분모 == 0 or y분모 == 0:
        return 0
    return 분자 / (x분모 * y분모)

# ─────────────────────────────────────────────
# 그래프 크기 설정 (가로 좁게 + 세로 길게 = 깍두기 탈출!)
# ─────────────────────────────────────────────
그래프높이 = 600   # 세로 길이 (클수록 막대 차이가 잘 보임)

def 막대그래프(데이터):
    # 화면을 [3, 2, 3] 비율로 나눠 가운데(2)에만 그래프 → 가로 좁게
    여백왼, 가운데, 여백오 = st.columns([3, 2, 3])
    with 가운데:
        st.bar_chart(데이터, height=그래프높이)

# ─────────────────────────────────────────────
# 1단계: 상관관계 분석
# ─────────────────────────────────────────────
st.header("1️⃣ 상관관계 분석: SNS 사용량과 무엇이 관련 있을까?")

분석대상 = ["수면시간", "학업성취도", "신체활동량", "스트레스수준", "불안수준", "중독수준"]
x값 = df["하루SNS사용시간"].tolist()

결과목록 = []
for 항목 in 분석대상:
    y값 = df[항목].tolist()
    r = 상관계수(x값, y값)
    if abs(r) < 0.1:
        해석 = "거의 관련 없음"
    elif abs(r) < 0.3:
        해석 = "약한 관련"
    elif abs(r) < 0.5:
        해석 = "보통 관련"
    else:
        해석 = "강한 관련"
    방향 = "정비례(같이 증가)" if r > 0 else "반비례(반대로 변함)"
    결과목록.append({
        "지표": 항목,
        "상관계수(r)": round(r, 3),
        "관련 정도": 해석,
        "방향": 방향
    })

상관표 = pd.DataFrame(결과목록)
st.dataframe(상관표, use_container_width=True)

st.subheader("📊 지표별 상관계수 막대그래프")
그래프데이터 = 상관표.set_index("지표")["상관계수(r)"]
막대그래프(그래프데이터)

st.info(
    "💡 상관계수(r)는 -1 ~ +1 사이의 값입니다. "
    "0에 가까울수록 관련이 약하고, ±1에 가까울수록 관련이 강합니다."
)

# ─────────────────────────────────────────────
# 2단계: 구간별 비교로 '임계점' 찾기
# ─────────────────────────────────────────────
st.header("2️⃣ '몇 시간부터' 부정적 영향이 커질까? (구간 분석)")

구간경계 = [0, 2, 4, 6, 8.1]
구간이름 = ["0~2시간", "2~4시간", "4~6시간", "6~8시간"]
df["SNS사용구간"] = pd.cut(df["하루SNS사용시간"], bins=구간경계,
                          labels=구간이름, right=False)

비교지표 = st.selectbox(
    "구간별로 비교할 지표를 선택하세요",
    ["수면시간", "학업성취도", "신체활동량", "스트레스수준", "불안수준"]
)

구간평균 = df.groupby("SNS사용구간")[비교지표].mean().round(2)
st.subheader(f"📊 SNS 사용 구간별 평균 {비교지표}")
막대그래프(구간평균)
st.dataframe(구간평균.rename(f"평균 {비교지표}"), use_container_width=True)

# ─────────────────────────────────────────────
# 3단계: 우울증 비율 분석
# ─────────────────────────────────────────────
st.header("3️⃣ SNS 사용 구간별 우울증 비율")

우울비율 = (df.groupby("SNS사용구간")["우울증여부"].mean() * 100).round(2)
st.subheader("📊 구간별 우울증 학생 비율 (%)")
막대그래프(우울비율)
st.dataframe(우울비율.rename("우울증 비율(%)"), use_container_width=True)

# ─────────────────────────────────────────────
# 4단계: 탐구 결론 자동 정리
# ─────────────────────────────────────────────
st.header("4️⃣ 탐구 결론 정리 도우미")

가장강한 = 상관표.loc[상관표["상관계수(r)"].abs().idxmax()]
st.success(
    f"분석 결과, 하루 SNS 사용시간과 가장 관련이 깊은 지표는 "
    f"**'{가장강한['지표']}'** 입니다. "
    f"(상관계수 r = {가장강한['상관계수(r)']}, {가장강한['관련 정도']}, {가장강한['방향']})"
)

